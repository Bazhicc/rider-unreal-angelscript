    object Factory {
        fun createElement(node: ASTNode?): PsiElement {
            requireNotNull(node)
            return when (val type = node.elementType) {
                ADD_EXPR -> AngelscriptAddExprImpl(node)
                ARGUMENT -> AngelscriptArgumentImpl(node)
                ARG_LIST -> AngelscriptArgListImpl(node)
                ASSET_DECL -> AngelscriptAssetDeclImpl(node)
                ASSIGNMENT_EXPR -> AngelscriptAssignmentExprImpl(node)
                BITWISE_AND_EXPR -> AngelscriptBitwiseAndExprImpl(node)
                BREAK_STATEMENT -> AngelscriptBreakStatementImpl(node)
                CASE_STATEMENT -> AngelscriptCaseStatementImpl(node)
                CAST_EXPR -> AngelscriptCastExprImpl(node)
                CLASS_DECL -> AngelscriptClassDeclImpl(node)
                COMMA_EXPR -> AngelscriptCommaExprImpl(node)
                COMMENT_NODE -> AngelscriptCommentImpl(node)
                COMPOUND_STATEMENT -> AngelscriptCompoundStatementImpl(node)
                CONDITIONAL_EXPR -> AngelscriptConditionalExprImpl(node)
                CONSTRUCTOR_DECL -> AngelscriptConstructorDeclImpl(node)
                CONTINUE_STATEMENT -> AngelscriptContinueStatementImpl(node)
                DEFAULT_VALUE_DECL -> AngelscriptDefaultValueDeclImpl(node)
                DELEGATE_DECL -> AngelscriptDelegateDeclImpl(node)
                DO_STATEMENT -> AngelscriptDoStatementImpl(node)
                ELSE_CLAUSE -> AngelscriptElseClauseImpl(node)
                ENUM_DECL -> AngelscriptEnumDeclImpl(node)
                ENUM_VARIANT -> AngelscriptEnumVariantImpl(node)
                EQUALITY_EXPR -> AngelscriptEqualityExprImpl(node)
                EVENT_DECL -> AngelscriptEventDeclImpl(node)
                EXCLUSIVE_OR_EXPR -> AngelscriptExclusiveOrExprImpl(node)
                EXPRESSION_STATEMENT -> AngelscriptExpressionStatementImpl(node)
                FOREACH_STATEMENT -> AngelscriptForeachStatementImpl(node)
                FOR_STATEMENT -> AngelscriptForStatementImpl(node)
                FUNCTION_DECL -> AngelscriptFunctionDeclImpl(node)
                F_STRING_EXPR -> AngelscriptFStringExprImpl(node)
                F_STRING_FORMAT_SPEC -> AngelscriptFStringFormatSpecImpl(node)
                F_STRING_INTERP -> AngelscriptFStringInterpImpl(node)
                IF_DEF_BLOCK -> AngelscriptIfDefBlockImpl(node)
                IF_DEF_BRANCH -> AngelscriptIfDefBranchImpl(node)
                IF_STATEMENT -> AngelscriptIfStatementImpl(node)
                INCLUSIVE_OR_EXPR -> AngelscriptInclusiveOrExprImpl(node)
                INIT_LIST_EXPR -> AngelscriptInitListExprImpl(node)
                INTERFACE_DECL -> AngelscriptInterfaceDeclImpl(node)
                LOGICAL_AND_EXPR -> AngelscriptLogicalAndExprImpl(node)
                LOGICAL_OR_EXPR -> AngelscriptLogicalOrExprImpl(node)
                MIXIN_DECL -> AngelscriptMixinDeclImpl(node)
                MULTIPLY_EXPR -> AngelscriptMultiplyExprImpl(node)
                NAMESPACE_DECL -> AngelscriptNamespaceDeclImpl(node)
                PARAMETER_DECL -> AngelscriptParameterDeclImpl(node)
                PARAMETER_LIST -> AngelscriptParameterListImpl(node)
                PARENTHESIZED_EXPR -> AngelscriptParenthesizedExprImpl(node)
                POSTFIX_EXPR -> AngelscriptPostfixExprImpl(node)
                PP_DEFINE_DIRECTIVE -> AngelscriptPPDefineDirectiveImpl(node)
                PRIMARY_EXPR -> AngelscriptPrimaryExprImpl(node)
                RELATIONAL_EXPR -> AngelscriptRelationalExprImpl(node)
                RETURN_STATEMENT -> AngelscriptReturnStatementImpl(node)
                SCOPE_REF -> AngelscriptScopeRefImpl(node)
                SHIFT_EXPR -> AngelscriptShiftExprImpl(node)
                STATEMENT -> AngelscriptStatementImpl(node)
                STRING_CONCAT_EXPR -> AngelscriptStringConcatExprImpl(node)
                STRUCT_DECL -> AngelscriptStructDeclImpl(node)
                SWITCH_STATEMENT -> AngelscriptSwitchStatementImpl(node)
                TYPEDEF_DECL -> AngelscriptTypedefDeclImpl(node)
                TYPE_ARGUMENT -> AngelscriptTypeArgumentImpl(node)
                TYPE_REF -> AngelscriptTypeRefImpl(node)
                UNARY_EXPR -> AngelscriptUnaryExprImpl(node)
                U_CLASS_DECL -> AngelscriptUClassDeclImpl(node)
                U_ENUM_DECL -> AngelscriptUEnumDeclImpl(node)
                U_FUNCTION_DECL -> AngelscriptUFunctionDeclImpl(node)
                U_INTERFACE_DECL -> AngelscriptUInterfaceDeclImpl(node)
                U_PROPERTY_DECL -> AngelscriptUPropertyDeclImpl(node)
                U_STRUCT_DECL -> AngelscriptUStructDeclImpl(node)
                VARIABLE_ACCESS_EXPR -> AngelscriptVariableAccessExprImpl(node)
                VARIABLE_DECL -> AngelscriptVariableDeclImpl(node)
                WHILE_STATEMENT -> AngelscriptWhileStatementImpl(node)
                else -> error("Unknown element type: $type")
            }
        }
